import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
// Recolour the Plump Flat SVGs into a React icon set.
// Ink and accents come from src-shared/ui/tokens.css variables.
const svgDir=new URL('../src-shared/ui/icons/svg/',import.meta.url);
const out=new URL('../src-shared/ui/app-icons.jsx',import.meta.url);
const accents={
  '01-robot':'--op-color-icon-accent',
  '02-briefcase':'--op-color-icon-accent-deep',
  '03-fork-knife':'--op-color-icon-accent',
  '04-office-building':'--op-color-icon-accent-deep',
  '05-desktop-computer':'--op-color-icon-accent',
  '06-mobile-phone':'--op-color-icon-accent-deep',
  '07-stopwatch':'--op-color-icon-accent',
  '08-money-bag':'--op-color-icon-accent-deep',
  '09-pill':'--op-color-icon-accent',
  '10-framed-picture':'--op-color-icon-accent-deep',
  '11-bed':'--op-color-icon-accent',
  '12-shopping-bags':'--op-color-icon-accent-deep',
  '13-envelope':'--op-color-icon-accent',
  '14-postbox':'--op-color-icon-accent-deep',
  '15-notepad':'--op-color-icon-accent',
  '16-clipboard':'--op-color-icon-accent-deep',
  '17-paperclip':'--op-color-icon-accent',
  '18-unlocked-padlock':'--op-color-icon-accent-deep'
};
const labels={
  robot:'Robot',briefcase:'Briefcase','fork-knife':'Fork & knife','office-building':'Office building',
  'desktop-computer':'Desktop computer','mobile-phone':'Mobile phone',stopwatch:'Stopwatch','money-bag':'Money bag',
  pill:'Pill','framed-picture':'Framed picture',bed:'Bed','shopping-bags':'Shopping bags',envelope:'Envelope',
  postbox:'Postbox',notepad:'Notepad',clipboard:'Clipboard',paperclip:'Paperclip','unlocked-padlock':'Unlocked padlock'
};
// Closest icon for each NOVA App. Icons without an app stay in the set.
const appFor={
  equipment:'briefcase',
  repair:'office-building',
  assets:'desktop-computer',
  leave:'clipboard',
  attendance:'stopwatch',
  tasks:'notepad',
  expense:'money-bag',
  plants:'framed-picture',
  clients:'envelope'
};
const appNames={
  equipment:'器材管理',repair:'設備管理中心',assets:'IT Asset Management',leave:'請假管理',
  attendance:'我的出勤',tasks:'專案待辦',expense:'費用報帳',plants:'澆水總覽',clients:'客戶跟進'
};
const files=readdirSync(svgDir).filter(name=>name.endsWith('.svg')).sort();
const icons={};
for(const file of files){
  const accent=accents[file.replace('.svg','')];
  if(!accent) throw new Error('Missing accent for '+file);
  const raw=readFileSync(new URL(file,svgDir),'utf8');
  const inner=raw.replace(/^[\s\S]*?<svg[^>]*>/,'').replace(/<\/svg>\s*$/,'')
    .replace(/#000000/gi,'var(--op-color-icon-ink)')
    .replace(/#(?:46C7FF|6DE659|FFBE26|FF94AB|FF6F42)/gi,`var(${accent})`)
    .replace(/id="[^"]+"/g,'id="__CLIP__"')
    .replace(/url\(#[^)]+\)/g,'url(#__CLIP__)');
  if(/#[0-9a-fA-F]{3,8}/.test(inner)) throw new Error('Unmapped colour in '+file);
  const name=file.replace(/^\d+-/ ,'').replace('.svg','');
  icons[name]={accent:accent.endsWith('deep')?'deep':'accent',markup:inner.trim()};
}
const catalog=Object.entries(icons).map(([name,icon])=>{
  const apps=Object.entries(appFor).filter(([,iconName])=>iconName===name).map(([id])=>({id,name:appNames[id]}));
  return {name,label:labels[name]||name,accent:icon.accent,apps};
});
const body=`import React,{useId} from 'react';
// Generated by scripts/build-app-icons.mjs from src-shared/ui/icons/svg.
// Recolour by editing tokens, then run: npm run icons
const ICONS=${JSON.stringify(icons,null,2)};
export const APP_ICON_CATALOG=${JSON.stringify(catalog,null,2)};
export const APP_ICON_FOR=${JSON.stringify(appFor,null,2)};
export function AppIcon({name='robot',size=24,title,className='',...props}){
  const clip=useId().replace(/:/g,'');
  const icon=ICONS[name]||ICONS.robot;
  const markup=icon.markup.replaceAll('__CLIP__',clip);
  return <svg className={\`op-app-icon op-app-icon--\${icon.accent} \${className}\`.trim()} width={size} height={size} viewBox="0 0 48 48" role={title?'img':'presentation'} aria-hidden={title?undefined:true} aria-label={title} focusable="false" dangerouslySetInnerHTML={{__html:markup}} {...props}/>;
}
`;
writeFileSync(out,body);
console.log('Wrote',icons && Object.keys(icons).length,'icons');
